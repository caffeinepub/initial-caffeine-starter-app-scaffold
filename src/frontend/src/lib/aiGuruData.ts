// Deterministic seed based on date + rashi index
function getDaySeed(rashiIndex: number): number {
  const now = new Date();
  const dayOfYear = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / 86400000,
  );
  return (dayOfYear * 13 + rashiIndex * 7 + now.getFullYear()) % 1000;
}

export function getDailyBhavishya(rashiId: string): DailyBhavishya {
  const rashiIndex = RASHIS.findIndex((r) => r.id === rashiId);
  const seed = getDaySeed(rashiIndex);

  const loveSet = seed % 2;
  const careerSet = (seed + 1) % 2;
  const healthSet = (seed + 2) % 2;
  const financeSet = (seed + 3) % 2;

  const loveIdx = (seed + rashiIndex) % LOVE_TEMPLATES[loveSet].length;
  const careerIdx =
    (seed + rashiIndex + 1) % CAREER_TEMPLATES[careerSet].length;
  const healthIdx =
    (seed + rashiIndex + 2) % HEALTH_TEMPLATES[healthSet].length;
  const financeIdx =
    (seed + rashiIndex + 3) % FINANCE_TEMPLATES[financeSet].length;
  const colorSet = seed % 2;
  const colorIdx = (seed + rashiIndex) % LUCKY_COLORS[colorSet].length;
  const luckyNum = ((seed + rashiIndex * 3) % 9) + 1;
  const timeIdx = (seed + rashiIndex) % LUCKY_TIMES.length;
  const overallIdx = (seed + rashiIndex * 2) % OVERALL_PREDICTIONS.length;
  const tipIdx = (seed + rashiIndex * 5) % DAILY_TIPS.length;

  return {
    rashi: rashiId,
    overall: OVERALL_PREDICTIONS[overallIdx],
    aspects: [
      {
        label: "प्रेम और संबंध",
        icon: "❤️",
        content: LOVE_TEMPLATES[loveSet][loveIdx],
      },
      {
        label: "करियर और व्यापार",
        icon: "💼",
        content: CAREER_TEMPLATES[careerSet][careerIdx],
      },
      {
        label: "स्वास्थ्य",
        icon: "🌿",
        content: HEALTH_TEMPLATES[healthSet][healthIdx],
      },
      {
        label: "धन और वित्त",
        icon: "💰",
        content: FINANCE_TEMPLATES[financeSet][financeIdx],
      },
    ],
    luckyColor: LUCKY_COLORS[colorSet][colorIdx],
    luckyNumber: luckyNum,
    luckyTime: LUCKY_TIMES[timeIdx],
    tip: DAILY_TIPS[tipIdx],
  };
}

